export type SiteliyoLocale = "en" | "tr";

export const SITELIYO_LOCALE_COOKIE = "siteliyo-locale";
export const SITELIYO_LOCALE_STORAGE_KEY = "siteliyo-locale";

export function resolveSiteliyoLocale(value: string | null | undefined): SiteliyoLocale {
  return value === "tr" ? "tr" : "en";
}

export function getLocaleBadge(locale: SiteliyoLocale) {
  return locale.toUpperCase();
}

export function getLocaleName(locale: SiteliyoLocale) {
  return locale === "tr" ? "Turkish" : "English";
}

